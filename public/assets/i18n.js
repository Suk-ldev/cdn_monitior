const DICTS = { zh, en };

export function createI18n(initial = 'zh') {
  let lang = DICTS[initial] ? initial : 'zh';
  return {
    get lang() {
      return lang;
    },
    set(next) {
      if (DICTS[next]) lang = next;
    },
    t(key, fallback) {
      return DICTS[lang][key] ?? DICTS.zh[key] ?? fallback ?? key;
    },
    get locale() {
      return lang === 'en' ? 'en' : 'zh-CN';
    }
  };
}
